def lake():
    """420x260 lake: sandy shore, gradient water, foam, lilies, sparkles."""
    img = new(420, 260)
    d = ImageDraw.Draw(img)
    r = rng(112)
    cx, cy, rx, ry = 210, 130, 204, 124
    # outer dark rim + sand ring
    d.ellipse([cx - rx, cy - ry, cx + rx, cy + ry], fill=C("K"))
    d.ellipse([cx - rx + 5, cy - ry + 5, cx + rx - 5, cy + ry - 5], fill=C("tan"))
    speckle(d, cx - rx + 8, cy - ry + 8, cx + rx - 8, cy + ry - 8,
            ["cream", "brown"], r, 200)
    # water with dithered depth gradient
    wx0, wy0, wx1, wy1 = cx - rx + 20, cy - ry + 20, cx + rx - 20, cy + ry - 20
    d.ellipse([wx0, wy0, wx1, wy1], fill=C("sky"))
    for y in range(wy0, wy1 + 1):
        t = (y - wy0) / max(1, (wy1 - wy0))
        for x in range(wx0, wx1 + 1):
            if ((x - cx) / (rx - 20)) ** 2 + ((y - cy) / (ry - 20)) ** 2 < 1:
                if r.random() < t * 0.85:
                    d.point((x, y), fill=C("blued"))
    # shore foam scallops
    for i in range(48):
        ang = 2 * math.pi * i / 48
        fx = int(cx + (rx - 24) * math.cos(ang))
        fy = int(cy + (ry - 24) * math.sin(ang))
        d.ellipse([fx - 5, fy - 2, fx + 5, fy + 3], fill=C("white"))
        d.ellipse([fx - 3, fy - 1, fx + 3, fy + 2], fill=C("sky"))
    # wave lines
    for _ in range(26):
        x = r.randint(wx0 + 10, wx1 - 20)
        y = r.randint(wy0 + 10, wy1 - 10)
        if ((x - cx) / (rx - 30)) ** 2 + ((y - cy) / (ry - 30)) ** 2 < 1:
            d.line([(x, y), (x + 10, y)], fill=C("white"))
            d.line([(x + 2, y + 2), (x + 8, y + 2)], fill=C("sky"))
    # lily pads + blossom
    for (x, y) in [(150, 150), (260, 110), (300, 170), (120, 100)]:
        d.ellipse([x - 8, y - 5, x + 8, y + 5], fill=C("K"))
        d.pieslice([x - 7, y - 4, x + 7, y + 4], 20, 340, fill=C("green"))
        d.line([(x, y), (x + 4, y - 2)], fill=C("greend"))
        if (x + y) % 2 == 0:
            for px_, py_ in [(x - 3, y - 7), (x + 2, y - 8), (x, y - 5)]:
                d.ellipse([px_ - 2, py_ - 2, px_ + 2, py_ + 2], fill=C("sakura"),
                          outline=C("sakurad"))
    # sparkles
    for _ in range(30):
        x = r.randint(wx0 + 6, wx1 - 6)
        y = r.randint(wy0 + 6, wy1 - 6)
        if ((x - cx) / (rx - 30)) ** 2 + ((y - cy) / (ry - 30)) ** 2 < 1:
            d.point((x, y), fill=C("white"))
            d.point((x + 1, y), fill=C("sky"))
    return img



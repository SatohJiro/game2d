def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    manifest = []
    for name, (fn, rel) in BUILDINGS.items():
        img = fn()
        img.save(os.path.join(args.out, name + ".png"))
        manifest.append({"path": rel, "width": img.size[0], "height": img.size[1]})
    with open(os.path.join(args.out, "town_manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=1)
    print("generated %d town sprites -> %s" % (len(manifest), args.out))


if __name__ == "__main__":
    main()

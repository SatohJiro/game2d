def C(name):
    return PAL[name] + (255,)


def new(w, h):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def orect(d, x0, y0, x1, y1, fill, outline="K", ow=2):
    d.rectangle([x0, y0, x1, y1], fill=C(outline))
    d.rectangle([x0 + ow, y0 + ow, x1 - ow, y1 - ow], fill=C(fill))


def roof_poly(d, points, fill="roof", shade="roofd"):
    d.polygon(points, fill=C("K"))
    inset = [(x, y) for x, y in points]
    # simple inset by moving toward centroid
    cx = sum(p[0] for p in points) / len(points)
    cy = sum(p[1] for p in points) / len(points)
    inset = [(x + (cx - x) * 0.08, y + (cy - y) * 0.08) for x, y in points]
    d.polygon(inset, fill=C(fill))



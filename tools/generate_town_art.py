def C(name):
    return PAL[name] + (255,)


def new(w, h):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def rng(seed):
    return random.Random(seed)


# ---------------------------------------------------------------- helpers
def rect(d, x0, y0, x1, y1, fill, outline=None, ow=1):
    """Filled rect with optional outline. fill=None draws outline only."""
    if outline is not None:
        d.rectangle([x0, y0, x1, y1], fill=C(outline))
        if fill is not None:
            d.rectangle([x0 + ow, y0 + ow, x1 - ow, y1 - ow], fill=C(fill))
    elif fill is not None:
        d.rectangle([x0, y0, x1, y1], fill=C(fill))


def dither_v(d, x0, y0, x1, y1, c_top, c_bottom):
    """Vertical dithered gradient between two palette colors."""
    h = max(1, y1 - y0)
    for y in range(y0, y1 + 1):
        t = (y - y0) / h
        for x in range(x0, x1 + 1):
            if ((x + y) % 2 == 0 and t < 0.5) or ((x * 7 + y * 13) % 10 < t * 10):
                d.point((x, y), fill=C(c_bottom))
            else:
                d.point((x, y), fill=C(c_top))


def speckle(d, x0, y0, x1, y1, colors, r, n):
    for _ in range(n):
        x = r.randint(x0, x1)
        y = r.randint(y0, y1)
        d.point((x, y), fill=C(r.choice(colors)))


def bricks(d, x0, y0, x1, y1, bh, brick, mortar, r, speck=True):
    """Brick courses with offset rows."""
    rect(d, x0, y0, x1, y1, mortar)
    row = 0
    y = y0
    while y < y1:
        off = (row % 2) * 6
        for x in range(x0 - 12 + off, x1 + 1, 12):
            bx0, bx1 = max(x, x0), min(x + 10, x1)
            by0, by1 = y + 1, min(y + bh - 1, y1)
            if bx1 > bx0 and by1 > by0:
                rect(d, bx0, by0, bx1, by1, brick)
                if speck and r.random() < 0.5:
                    d.point((r.randint(bx0 + 1, bx1), r.randint(by0 + 1, by1)),
                            fill=C(mortar))
        y += bh
        row += 1


def planks_v(d, x0, y0, x1, y1, wood, woodd, r, pw=6):
    """Vertical wood planks with grain."""
    rect(d, x0, y0, x1, y1, wood)
    for x in range(x0, x1 + 1, pw):
        d.line([(x, y0), (x, y1)], fill=C(woodd))
        gx1 = min(x + pw - 2, x1)
        if gx1 <= x + 1:
            continue
        for _ in range((y1 - y0) // 9):
            gx = r.randint(x + 1, gx1)
            gy = r.randint(y0 + 2, y1 - 2)
            d.line([(gx, gy), (gx, gy + 3)], fill=C(woodd))


def planks_h(d, x0, y0, x1, y1, wood, woodd, r, ph=5):
    rect(d, x0, y0, x1, y1, wood)
    for y in range(y0, y1 + 1, ph):
        d.line([(x0, y), (x1, y)], fill=C(woodd))


def window(d, x, y, w, h, lit=False):
    """Lattice window: dark frame, glass with diagonal reflection."""
    rect(d, x, y, x + w, y + h, "night", outline="K", ow=1)
    gx0, gy0, gx1, gy1 = x + 2, y + 2, x + w - 2, y + h - 2
    glass = "glow" if lit else "night"
    rect(d, gx0, gy0, gx1, gy1, glass)
    if not lit:
        # sky reflection diagonal
        for i in range(min(w, h) - 3):
            d.point((gx0 + 1 + i, gy0 + 1 + i), fill=C("sky"))
            if i + 1 < min(w, h) - 3:
                d.point((gx0 + 2 + i, gy0 + 1 + i), fill=C("blued"))
    # mullions
    d.line([(x + w // 2, gy0), (x + w // 2, gy1)], fill=C("K"))
    d.line([(gx0, y + h // 2), (gx1, y + h // 2)], fill=C("K"))
    # sill
    rect(d, x - 1, y + h + 1, x + w + 1, y + h + 3, "woodd", outline="K", ow=1)


def star(d, cx, cy, r, col):
    pts = []
    for i in range(10):
        ang = -math.pi / 2 + i * math.pi / 5
        rr = r if i % 2 == 0 else r * 0.45
        pts.append((cx + rr * math.cos(ang), cy + rr * math.sin(ang)))
    d.polygon(pts, fill=C(col))


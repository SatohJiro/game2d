def _japan_roof(d, cx, y_apex, half_base, y_eave, r, tile="roof", tiled="roofd"):
    """Tiled gable roof with ridge caps and flared eaves."""
    # main slope
    d.polygon([(cx - half_base, y_eave), (cx, y_apex), (cx + half_base, y_eave)],
              fill=C("K"))
    d.polygon([(cx - half_base + 3, y_eave - 2), (cx, y_apex + 4),
               (cx + half_base - 3, y_eave - 2)], fill=C(tile))
    # tile rows
    rows = max(2, (y_eave - y_apex) // 8)
    for i in range(rows):
        t0 = i / rows
        t1 = (i + 1) / rows
        ya = int(y_apex + (y_eave - y_apex) * t0) + 2
        yb = int(y_apex + (y_eave - y_apex) * t1) + 2
        h0 = half_base * (1 - t0 * 0.92)
        h1 = half_base * (1 - t1 * 0.92)
        n = max(3, int(h1 * 2 / 8))
        for k in range(n):
            tx = cx - h1 + (2 * h1) * (k + 0.5) / n
            d.arc([tx - 4, yb - 5, tx + 4, yb + 3], 0, 180, fill=C(tiled))
        d.line([(cx - h1, yb), (cx + h1, yb)], fill=C(tiled))
    # ridge caps
    for k in range(-2, 3):
        d.ellipse([cx + k * 8 - 4, y_apex - 2, cx + k * 8 + 4, y_apex + 6],
                  fill=C(tiled), outline=C("K"))
    # flared eaves
    d.polygon([(cx - half_base - 6, y_eave + 2), (cx - half_base + 4, y_eave - 6),
               (cx + half_base - 4, y_eave - 6), (cx + half_base + 6, y_eave + 2)],
              fill=C("K"))
    d.polygon([(cx - half_base - 4, y_eave), (cx - half_base + 4, y_eave - 4),
               (cx + half_base - 4, y_eave - 4), (cx + half_base + 4, y_eave)],
              fill=C(tiled))


def _machiya_walls(d, x0, y0, x1, y1, r):
    """Plaster walls with dark wood frame (machiya style)."""
    rect(d, x0, y0, x1, y1, "plas", outline="K", ow=2)
    # subtle plaster texture
    speckle(d, x0 + 3, y0 + 3, x1 - 3, y1 - 3, ["plasd"], r, 40)
    # corner posts + beams
    for x in (x0 + 2, x1 - 4):
        rect(d, x, y0, x + 2, y1, "woodd")
    rect(d, x0, y0, x1, y0 + 4, "woodd")      # top beam
    rect(d, x0, y1 - 6, x1, y1 - 2, "woodd")  # bottom beam
    # wood grain on beams
    for x in range(x0 + 6, x1 - 4, 8):
        d.point((x, y0 + 2), fill=C("wood"))



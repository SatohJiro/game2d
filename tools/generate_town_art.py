"""Generate original CC0 town art for Paloria Luminous Town (AT-B, refreshed).

Anime-town pixel art drawn with PIL. Every pixel color is constrained to the
validator palette (PALORIA16 + AT town extensions, see
tools/validate_town_art.py) so the art gate stays green. Canvas sizes match the
greybox footprints in systems/town/town_layout.gd exactly.

Provenance: GENERATED by project tool, license CC0-1.0, author "Paloria project".
Third-party evaluation (2026-10-08): Kenney "Tiny Town"/"Tiny Dungeon"/
"Tiny Farm" packs (CC0-1.0, kenney.nl) were downloaded and evaluated as a
sprite source. Rejected for direct use: western-medieval style clashes with the
anime/Japanese town direction (torii, shrine, sakura, vending machines), and
the character sprites are single-frame with no 4-direction walk cycles, so they
cannot satisfy the hero/pet animation contracts. Original art keeps the style
coherent and the provenance clean.

Usage:
    python3 tools/generate_town_art.py --out /tmp/paloria_town
"""

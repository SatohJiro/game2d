# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="output directory for PNGs")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    manifest = []
    # items
    for name, rows in ITEMS.items():
        rel = "assets/items/%s.png" % name
        img = from_ascii(rows)
        img.save(os.path.join(args.out, "items_%s.png" % name))
        manifest.append({"path": rel, "width": 16, "height": 16})
    strip = Image.new("RGBA", (64, 16), (0, 0, 0, 0))
    for i, rows in enumerate(CROP_STAGES):
        f = from_ascii(rows)
        strip.paste(f, (i * 16, 0), f)
    strip.save(os.path.join(args.out, "items_crop_stages.png"))
    manifest.append({"path": "assets/items/crop_stages.png", "width": 64, "height": 16})
    for rel, fn in list(BUILDINGS.items()) + list(TILES.items()) + list(FX.items()):
        img = fn()
        flat = "misc_" + rel.replace("assets/", "").replace("/", "_")
        img.save(os.path.join(args.out, flat))
        manifest.append({"path": rel, "width": img.size[0], "height": img.size[1]})
    with open(os.path.join(args.out, "generation_manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=1)
    print("generated %d sprites -> %s" % (len(manifest), args.out))


if __name__ == "__main__":
    main()

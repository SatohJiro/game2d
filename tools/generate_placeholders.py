GENERATED = []  # (relative_path, width, height, kind)


def from_ascii(rows):
    h = len(rows)
    w = max(len(r) for r in rows)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "." or ch == " ":
                continue
            if ch not in PALETTE:
                raise ValueError("unknown palette char %r" % ch)
            px[x, y] = PALETTE[ch] + (255,)
    return img


def save(img, rel_path):
    GENERATED.append((rel_path, img.size[0], img.size[1], "texture"))



def _pal(name):
    return PALETTE[name] + (255,)


def _outlined_rect(d, x0, y0, x1, y1, fill, outline="K"):
    d.rectangle([x0, y0, x1, y1], fill=_pal(outline))
    d.rectangle([x0 + 1, y0 + 1, x1 - 1, y1 - 1], fill=_pal(fill))



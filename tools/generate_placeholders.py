def _glow_circle(size, inner, mid):
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = size // 2
    for r in range(c, 0, -1):
        t = r / c
        if t > 0.55:
            col = mid
        elif t > 0.25:
            col = inner
        else:
            col = "N"
        d.ellipse([c - r, c - r, c + r, c + r], fill=_pal(col))
    return img


def fx_frame_orb(frame, total, size, col1, col2):
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = size // 2
    rad = c - 2 - (frame % 2)
    d.ellipse([c - rad, c - rad, c + rad, c + rad], fill=_pal("K"))
    d.ellipse([c - rad + 1, c - rad + 1, c + rad - 1, c + rad - 1], fill=_pal(col1))
    d.ellipse([c - rad + 3, c - rad + 3, c + rad - 3, c + rad - 3], fill=_pal(col2))
    d.point((c - 2, c - 2), fill=_pal("N"))
    # motion streak
    for i in range(frame):
        d.point((2 + i * 2, c), fill=_pal(col1))
    return img



import random


def _seeded(s):
    return random.Random(s)


def tile_grass_cell(d, ox, oy, rng):
    base = "L"
    for y in range(16):
        for x in range(16):
            r = rng.random()
            c = base
            if r < 0.12: c = "l"
            elif r < 0.18: c = "W" if rng.random() < 0.5 else "l"
            d.point((ox + x, oy + y), fill=_pal(c))
    # occasional blade tufts
    for _ in range(3):
        x, y = rng.randint(ox + 1, ox + 14), rng.randint(oy + 4, oy + 14)
        d.line([(x, y), (x, y - 2)], fill=_pal("l"))


def tile_world_grass_tiled():
    img = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    rng = _seeded(7)
    for cy in range(16):
        for cx in range(16):
            tile_grass_cell(d, cx * 16, cy * 16, rng)
    return img


